const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../../Tools/Host/wwwroot/index.html'), 'utf8');
const nodes = new Map();
const node = id => { if (!nodes.has(id)) nodes.set(id, { value: '', textContent: '', innerHTML: '', checked: false, hidden: false, pause() {}, removeAttribute() {} }); return nodes.get(id); };
const writes = [];
const sandbox = { $: node, esc: String, api: async (url, method, body) => { writes.push({ url, method, body }); },
  logLine() {}, alert(message) { throw new Error(message); }, invalidateDailyPlan() {} };
vm.createContext(sandbox);
const start = html.indexOf('  const ROLE_LABELS =');
const end = html.indexOf('  function historyWindowMin(', start);
vm.runInContext(html.slice(start, end), sandbox);
vm.runInContext(`refreshProviders = async () => {}; renderRoleFilter = () => {}; renderModelList = () => {};
providerCache = [{id:'native',type:'openrouter_decisions',model:'typesafe/jev-1.14',baseUrl:'https://openrouter.ai/api',
hasApiKey:true,hasRelayKey:true,decisionMode:'direct'}]; selectedProviderId='native';`, sandbox);
const provider = vm.runInContext('providerCache[0]', sandbox);
sandbox.fillProviderForm(provider);
assert.equal(node('decisionOptions').hidden, false);
assert.equal(node('relayKeyField').hidden, true);
assert.equal(node('apiKey').value, '');
assert.equal(node('relayKey').value, '');
assert.equal(node('thinking').disabled, true);
assert.match(node('decisionUrlHint').textContent, /https:\/\/openrouter.ai\/api/);
node('decisionMode').value = 'relay';
sandbox.changeDecisionMode();
assert.equal(node('baseUrl').value, '', '切换专用中转不能沿用官方直连基址');
assert.equal(node('relayKeyField').hidden, false);
node('baseUrl').value = 'https://relay.example/tracesoul';
node('relayKey').value = 'synthetic-relay-key';
(async () => {
  await sandbox.saveProvider();
  assert.equal(writes.length, 1, '保存不隐式推理');
  assert.equal(writes[0].body.decisionMode, 'relay');
  assert.equal(writes[0].body.baseUrl, 'https://relay.example/tracesoul');
  assert.equal(writes[0].body.relayKey, 'synthetic-relay-key');
  assert.equal(writes[0].body.apiKey, '', '保留已有上游 Key');
  node('relayKey').value = '';
  node('clearRelayKey').checked = true;
  await sandbox.saveProvider();
  assert.equal(writes[1].body.clearRelayKey, true);
  sandbox.fillProviderForm({ id: 'chat', type: 'openai_chat_completion', hasApiKey: true });
  assert.equal(node('decisionOptions').hidden, true);
  assert.equal(node('relayKey').value, '');
  assert.equal(node('clearRelayKey').checked, false);
  assert.equal(node('thinking').disabled, false);
  console.log('Decisions UI checks passed: mode, base URL, credential preservation/clear, no implicit calls and chat compatibility.');
})().catch(e => { console.error(e); process.exitCode = 1; });
